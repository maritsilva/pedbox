// Height percentile index mapping: [p5, p10, p25, p50, p75, p90, p95]
const HEIGHT_P_IDX = [5, 10, 25, 50, 75, 90, 95];

/**
 * Interpolate BP at a specific height percentile for a given age and BP percentile
 */
function interpolateBPAtHeightP(table, age, bpPerc, heightP) {
  const row = table.find(r => r.age === Math.round(age));
  if (!row) return null;
  const arr = row[`p${bpPerc}`];
  if (!arr) return null;

  // Clamp heightP to [5, 95]
  const clampedHP = Math.max(5, Math.min(95, heightP));

  // Find bracket
  for (let i = 0; i < HEIGHT_P_IDX.length - 1; i++) {
    if (clampedHP >= HEIGHT_P_IDX[i] && clampedHP <= HEIGHT_P_IDX[i + 1]) {
      const frac = (clampedHP - HEIGHT_P_IDX[i]) / (HEIGHT_P_IDX[i + 1] - HEIGHT_P_IDX[i]);
      return arr[i] + frac * (arr[i + 1] - arr[i]);
    }
  }
  return arr[6]; // fallback to p95h
}

/**
 * Get BP percentile from a measured value, given age, sex, and height percentile
 * Uses linear interpolation between p50, p90, p95, p99 reference values
 */
export function getBPPercentile(type, sex, age, heightP, measuredBP) {
  const sysT = sex === 'M' ? sysBoys : sysGirls;
  const diasT = sex === 'M' ? diasBoys : diasGirls;
  const table = type === 'sys' ? sysT : diasT;

  const bp50 = interpolateBPAtHeightP(table, age, 50, heightP);
  const bp90 = interpolateBPAtHeightP(table, age, 90, heightP);
  const bp95 = interpolateBPAtHeightP(table, age, 95, heightP);
  const bp99 = interpolateBPAtHeightP(table, age, 99, heightP);

  if (bp50 == null) return null;

  // Interpolate percentile
  let percentile;
  if (measuredBP <= bp50) {
    percentile = 50 * (measuredBP / bp50);
  } else if (measuredBP <= bp90) {
    percentile = 50 + 40 * ((measuredBP - bp50) / (bp90 - bp50));
  } else if (measuredBP <= bp95) {
    percentile = 90 + 5 * ((measuredBP - bp90) / (bp95 - bp90));
  } else if (measuredBP <= bp99) {
    percentile = 95 + 4 * ((measuredBP - bp95) / (bp99 - bp95));
  } else {
    percentile = 99 + (measuredBP - bp99);
  }

  return {
    percentile: Math.min(99.9, Math.max(1, Math.round(percentile * 10) / 10)),
    ref: { p50: Math.round(bp50), p90: Math.round(bp90), p95: Math.round(bp95), p99: Math.round(bp99) },
  };
}

/**
 * Generate chart curve data for systolic or diastolic BP (at median height p50)
 * Returns array of { age, p50, p90, p95, p99 }
 */
export function generateBPCurve(type, sex, heightP = 50) {
  const sysT = sex === 'M' ? sysBoys : sysGirls;
  const diasT = sex === 'M' ? diasBoys : diasGirls;
  const table = type === 'sys' ? sysT : diasT;

  return table.map(row => ({
    age: row.age,
    p50: Math.round(interpolateBPAtHeightP(table, row.age, 50, heightP)),
    p90: Math.round(interpolateBPAtHeightP(table, row.age, 90, heightP)),
    p95: Math.round(interpolateBPAtHeightP(table, row.age, 95, heightP)),
    p99: Math.round(interpolateBPAtHeightP(table, row.age, 99, heightP)),
  }));
}

export function getBPCategory(sysPerc, diasPerc, ageLt13, sys, dias) {
  const maxP = Math.max(sysPerc, diasPerc);
  // AAP 2017 rules
  if (ageLt13) {
    if (maxP < 90) return { label: 'Normal', color: '#22c55e', bg: 'bg-green-100 text-green-800' };
    if (maxP < 95 || sys >= 120 || dias >= 80) return { label: 'Pressão Elevada', color: '#f59e0b', bg: 'bg-yellow-100 text-yellow-800' };
    if (maxP < 95 + 12 && sys < 130 && dias < 80) return { label: 'Hipertensão Estágio 1', color: '#f97316', bg: 'bg-orange-100 text-orange-800' };
    if (sys >= 140 || dias >= 90) return { label: 'Hipertensão Estágio 2', color: '#ef4444', bg: 'bg-red-100 text-red-800' };
    return { label: 'Hipertensão Estágio 1', color: '#f97316', bg: 'bg-orange-100 text-orange-800' };
  } else {
    // ≥13 years
    if (sys < 120 && dias < 80) return { label: 'Normal', color: '#22c55e', bg: 'bg-green-100 text-green-800' };
    if (sys < 130 && dias < 80) return { label: 'Pressão Elevada', color: '#f59e0b', bg: 'bg-yellow-100 text-yellow-800' };
    if (sys < 140 && dias < 90) return { label: 'Hipertensão Estágio 1', color: '#f97316', bg: 'bg-orange-100 text-orange-800' };
    return { label: 'Hipertensão Estágio 2', color: '#ef4444', bg: 'bg-red-100 text-red-800' };
  }
}