import {test,expect} from '@playwright/test';
for(const width of [390,1280])test(`novas calculadoras ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:900});
 await page.goto('/horas-de-vida');
 await page.getByLabel('Data de nascimento',{exact:true}).fill('2026-10-09');
 await page.getByLabel('Hora de nascimento',{exact:true}).fill('23:45');
 await page.getByLabel('Calcular até').selectOption('selected');
 await page.getByLabel('Data de referência',{exact:true}).fill('2026-10-11');
 await page.getByLabel('Hora de referência',{exact:true}).fill('01:15');
 await page.getByRole('button',{name:'Calcular horas de vida'}).click();
 await expect(page.getByRole('heading',{name:'25 horas e 30 minutos'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`artifacts/design/horas-de-vida-${width}.png`,fullPage:true});
 await page.getByLabel('Hora de nascimento',{exact:true}).fill('22:45');
 await expect(page.getByRole('region',{name:'Resultado das horas de vida'})).toHaveCount(0);
 await page.goto('/idade-gestacional');
 await page.getByLabel('Primeiro dia da última menstruação').fill('2024-01-01');
 await page.getByLabel('Data de referência',{exact:true}).fill('2024-02-29');
 await page.getByRole('button',{name:'Calcular idade gestacional'}).click();
 await expect(page.getByRole('heading',{name:'8 semanas e 3 dias'})).toBeVisible();
 await expect(page.locator('p').filter({hasText:/^07\/10\/2024$/})).toBeVisible();
 await page.getByLabel('Método de cálculo').selectOption('ivf');
 await expect(page.getByRole('region',{name:'Resultado da idade gestacional'})).toHaveCount(0);
 await page.getByLabel('Data da transferência',{exact:true}).fill('2026-01-01');
 await page.getByLabel('Data de referência',{exact:true}).fill('2026-01-01');
 await page.getByRole('button',{name:'Calcular idade gestacional'}).click();
 await expect(page.getByRole('heading',{name:'2 semanas e 5 dias'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`artifacts/design/idade-gestacional-${width}.png`,fullPage:true});
 await page.goto('/ferramentas');
 await page.getByLabel('Buscar ferramenta').fill('Horas de vida');
 await expect(page.getByRole('link',{name:/Horas de vida/})).toBeVisible();
});
test('horário atual avança automaticamente',async({page})=>{
 await page.clock.install({time:new Date('2026-10-10T12:00:00')});
 await page.goto('/horas-de-vida');
 await page.getByLabel('Data de nascimento',{exact:true}).fill('2026-10-10');
 await page.getByLabel('Hora de nascimento',{exact:true}).fill('10:00');
 await page.getByRole('button',{name:'Calcular horas de vida'}).click();
 await expect(page.getByRole('heading',{name:'2 horas e 0 minutos'})).toBeVisible();
 await page.clock.fastForward(60000);
 await expect(page.getByRole('heading',{name:'2 horas e 1 minutos'})).toBeVisible();
});
